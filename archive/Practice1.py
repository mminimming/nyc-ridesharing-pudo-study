def load_zone_centroids(zone_shp: str) -> pd.DataFrame:
    """
    Load all NYC taxi zone polygons and return LocationID centroids in WGS84.

    Borough filtering is NOT done here. Borough information is taken directly
    from taxi_zone_lookup.csv in load_taxi_requests(), because that is the
    same source used to interpret PULocationID/DOLocationID.
    """
    zones = gpd.read_file(zone_shp)

    # Normalize possible column-name variants.
    if "LocationID" not in zones.columns:
        candidates = [c for c in zones.columns if c.lower() == "locationid"]
        if candidates:
            zones = zones.rename(columns={candidates[0]: "LocationID"})
        else:
            raise ValueError(f"taxi_zones.shp must contain a LocationID column. Columns: {list(zones.columns)}")

    zones["LocationID"] = zones["LocationID"].astype(int)

    # Compute centroids in a projected CRS, then convert back to WGS84.
    zones_projected = zones.to_crs(epsg=2263)
    centroids = zones_projected.geometry.centroid
    centroids_wgs84 = gpd.GeoSeries(centroids, crs=zones_projected.crs).to_crs(epsg=4326)

    out = pd.DataFrame({
        "LocationID": zones["LocationID"].to_numpy(),
        "lon": centroids_wgs84.x.to_numpy(),
        "lat": centroids_wgs84.y.to_numpy(),
    })
    print(f"Loaded zone centroids from shapefile: {len(out)} zones")
    return out


def load_taxi_requests(
    taxi_file: str,
    zone_lookup_csv: str,
    zone_shp: str,
    G: nx.MultiDiGraph,
    start: Optional[str],
    end: Optional[str],
    max_requests: Optional[int],
    random_seed: int = 42,
) -> pd.DataFrame:
    """Load TLC taxi data and return Manhattan-to-Manhattan requests with snapped O/D nodes."""
    df = pd.read_parquet(taxi_file)

    if "tpep_pickup_datetime" not in df.columns:
        raise ValueError("Taxi parquet file must contain tpep_pickup_datetime.")

    if "passenger_count" in df.columns:
        df["passenger_count"] = df["passenger_count"].fillna(1).astype(int)
        df = df[df["passenger_count"] > 0].copy()
    else:
        df["passenger_count"] = 1

    if "trip_distance" in df.columns:
        df = df[df["trip_distance"].fillna(0) > 0].copy()

    pickup_min = df["tpep_pickup_datetime"].min()
    pickup_max = df["tpep_pickup_datetime"].max()

    if start is not None or end is not None:
        if start is None or end is None:
            raise ValueError("Use both --start and --end, or omit both to use the full parquet file.")
        start_ts = pd.Timestamp(start)
        end_ts = pd.Timestamp(end)
        df = df[(df["tpep_pickup_datetime"] >= start_ts) & (df["tpep_pickup_datetime"] < end_ts)].copy()
        if df.empty:
            raise ValueError(
                "No taxi trips were found in the selected time window.\n"
                f"Selected window: {start_ts} to {end_ts}\n"
                f"Available pickup_datetime range in this parquet: {pickup_min} to {pickup_max}\n"
                "Change --start and --end or omit both."
            )
        sim_start_ts = start_ts
    else:
        df = df.sort_values("tpep_pickup_datetime").copy()
        if df.empty:
            raise ValueError("The taxi parquet file contains no rows.")
        sim_start_ts = df["tpep_pickup_datetime"].min()
        print(
            "Using all taxi trips in the parquet file.\n"
            f"Available pickup_datetime range: {pickup_min} to {pickup_max}"
        )

    raw_coord_cols = [
        "pickup_longitude",
        "pickup_latitude",
        "dropoff_longitude",
        "dropoff_latitude",
    ]
    has_raw_coords = all(c in df.columns for c in raw_coord_cols)

    if has_raw_coords:
        df = df[
            df["pickup_longitude"].between(-74.03, -73.90)
            & df["dropoff_longitude"].between(-74.03, -73.90)
            & df["pickup_latitude"].between(40.68, 40.88)
            & df["dropoff_latitude"].between(40.68, 40.88)
        ].copy()
        if df.empty:
            raise ValueError("Taxi trips exist, but none passed the Manhattan coordinate filter.")

        if max_requests is not None and len(df) > max_requests:
            df = df.sample(max_requests, random_state=random_seed).sort_values("tpep_pickup_datetime")

        df = df.reset_index(drop=True)
        print(f"Filtered Manhattan taxi requests: {len(df)}")
        df["o_node"] = nearest_nodes(G, df["pickup_longitude"], df["pickup_latitude"])
        df["d_node"] = nearest_nodes(G, df["dropoff_longitude"], df["dropoff_latitude"])
        df["t_request"] = (df["tpep_pickup_datetime"] - sim_start_ts).dt.total_seconds()
        df["rid"] = np.arange(len(df))
        return df[["rid", "t_request", "o_node", "d_node", "passenger_count"]]

    required_zone_cols = ["PULocationID", "DOLocationID"]
    missing = [c for c in required_zone_cols if c not in df.columns]
    if missing:
        raise ValueError(
            "Taxi parquet file must contain either raw lon/lat columns or PULocationID/DOLocationID columns. "
            f"Missing: {missing}"
        )

    lookup = pd.read_csv(zone_lookup_csv)
    lookup.columns = [str(c).strip() for c in lookup.columns]
    required_lookup_cols = ["LocationID", "Borough", "Zone"]
    missing_lookup = [c for c in required_lookup_cols if c not in lookup.columns]
    if missing_lookup:
        raise ValueError(f"taxi_zone_lookup.csv missing columns: {missing_lookup}. Columns: {list(lookup.columns)}")

    lookup = lookup[["LocationID", "Borough", "Zone"]].copy()
    lookup["LocationID"] = lookup["LocationID"].astype(int)
    lookup["Borough"] = lookup["Borough"].astype(str).str.strip()
    lookup["Zone"] = lookup["Zone"].astype(str).str.strip()

    centroids = load_zone_centroids(zone_shp)
    zone_info = lookup.merge(centroids, on="LocationID", how="left")

    df["PULocationID"] = df["PULocationID"].astype(int)
    df["DOLocationID"] = df["DOLocationID"].astype(int)

    pu = zone_info.rename(
        columns={
            "LocationID": "PULocationID",
            "Borough": "PU_Borough",
            "Zone": "PU_Zone",
            "lon": "pu_lon",
            "lat": "pu_lat",
        }
    )
    do = zone_info.rename(
        columns={
            "LocationID": "DOLocationID",
            "Borough": "DO_Borough",
            "Zone": "DO_Zone",
            "lon": "do_lon",
            "lat": "do_lat",
        }
    )

    df = df.merge(pu, on="PULocationID", how="left")
    df = df.merge(do, on="DOLocationID", how="left")

    before_filter = len(df)
    df = df[
        (df["PU_Borough"].astype(str).str.strip().str.lower() == "manhattan")
        & (df["DO_Borough"].astype(str).str.strip().str.lower() == "manhattan")
        & df["pu_lon"].notna()
        & df["pu_lat"].notna()
        & df["do_lon"].notna()
        & df["do_lat"].notna()
    ].copy()
    print(f"Trips after Manhattan-to-Manhattan OD filter: {len(df)} / {before_filter}")

    if df.empty:
        raise ValueError(
            "No Manhattan-to-Manhattan trips remained after OD zone merge.\n"
            "Check taxi_zone_lookup.csv and taxi_zones.shp."
        )

    if max_requests is not None and len(df) > max_requests:
        df = df.sample(max_requests, random_state=random_seed).sort_values("tpep_pickup_datetime")

    df = df.reset_index(drop=True)
    print(f"Filtered Manhattan taxi requests: {len(df)}")

    df["o_node"] = nearest_nodes(G, df["pu_lon"], df["pu_lat"])
    df["d_node"] = nearest_nodes(G, df["do_lon"], df["do_lat"])
    df["t_request"] = (df["tpep_pickup_datetime"] - sim_start_ts).dt.total_seconds()
    df["rid"] = np.arange(len(df))
    return df[["rid", "t_request", "o_node", "d_node", "passenger_count"]]



def make_requests(df_req: pd.DataFrame, tt: TravelTimeCache) -> List[Request]:
    requests: List[Request] = []
    for row in tqdm(df_req.itertuples(index=False), total=len(df_req), desc="Computing direct times"):
        direct = tt.drive_time(int(row.o_node), int(row.d_node))
        if math.isfinite(direct) and direct > 0:
            requests.append(
                Request(
                    rid=int(row.rid),
                    t_request=float(row.t_request),
                    o_node=int(row.o_node),
                    d_node=int(row.d_node),
                    passengers=max(1, int(row.passenger_count)),
                    direct_drive=direct,
                )
            )
    return sorted(requests, key=lambda r: r.t_request)


def init_vehicles(G: nx.MultiDiGraph, n_vehicles: int, capacity: int, seed: int = 42) -> List[Vehicle]:
    rng = np.random.default_rng(seed)
    nodes = np.array(list(G.nodes()))
    chosen = rng.choice(nodes, size=n_vehicles, replace=True)
    return [Vehicle(vid=i, node=int(n), capacity=capacity) for i, n in enumerate(chosen)]


def clone_vehicles(vehicles: List[Vehicle]) -> List[Vehicle]:
    return [
        Vehicle(
            vid=v.vid,
            node=v.node,
            capacity=v.capacity,
            available_time=v.available_time,
            onboard=tuple(v.onboard),
            route=[Stop(s.rid, s.kind, s.node, s.scheduled_time) for s in v.route],
            vht=v.vht,
        )
        for v in vehicles
    ]


