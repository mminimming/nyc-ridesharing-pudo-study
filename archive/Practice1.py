def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--taxi-file", default=TLC_PARQUET)
    parser.add_argument("--zone-lookup", default=ZONE_LOOKUP_CSV)
    parser.add_argument("--zone-shp", default=ZONE_SHP)
    parser.add_argument("--start", default=None)
    parser.add_argument("--end", default=None)
    parser.add_argument("--n-vehicles", type=int, default=300)
    parser.add_argument("--vehicle-capacity", type=int, default=4)
    parser.add_argument("--max-requests", type=int, default=1500)
    parser.add_argument("--max-group-size", type=int, default=2)
    parser.add_argument("--mode", choices=["door", "pudo", "compare"], default="compare")
    parser.add_argument("--omega-walk-min", type=float, default=2.0)
    parser.add_argument("--omega-wait-min", type=float, default=5.0)
    parser.add_argument("--omega-delay-min", type=float, default=10.0)
    parser.add_argument("--candidate-limit", type=int, default=8)
    parser.add_argument("--batch-seconds", type=int, default=60)
    parser.add_argument("--output-prefix", default="nyc_pudo_gv_results")
    parser.add_argument(
        "--network-place",
        default="Manhattan, New York City, New York, USA",
        help="OSM place used to build the road graph. Default is Manhattan.",
    )
    args = parser.parse_args()

    params = SimParams(
        batch_seconds=args.batch_seconds,
        omega_wait=args.omega_wait_min * 60,
        omega_delay=args.omega_delay_min * 60,
        omega_walk=args.omega_walk_min * 60,
        pudo_candidate_limit=args.candidate_limit,
        max_group_size=args.max_group_size,
    )

    G = build_graph(args.network_place)
    tt = TravelTimeCache(G, params.walking_speed_mps)
    df_req = load_taxi_requests(
        taxi_file=str(args.taxi_file),
        zone_lookup_csv=str(args.zone_lookup),
        zone_shp=str(args.zone_shp),
        G=G,
        start=args.start,
        end=args.end,
        max_requests=args.max_requests,
    )
    requests = make_requests(df_req, tt)
    if not requests:
        raise ValueError("No valid requests remained after snapping and direct-time calculation.")

    base_vehicles = init_vehicles(G, args.n_vehicles, args.vehicle_capacity)
    summaries = []

    if args.mode in ["door", "compare"]:
        vehicles = clone_vehicles(base_vehicles)
        df_door = run_simulation(requests, vehicles, tt, params, allow_walking=False)
        df_door.to_csv(f"{args.output_prefix}_door.csv", index=False)
        s = summarize(df_door, vehicles)
        s["scenario"] = "door_to_door_gv"
        summaries.append(s)

    if args.mode in ["pudo", "compare"]:
        vehicles = clone_vehicles(base_vehicles)
        df_pudo = run_simulation(requests, vehicles, tt, params, allow_walking=True)
        df_pudo.to_csv(f"{args.output_prefix}_pudo.csv", index=False)
        s = summarize(df_pudo, vehicles)
        s["scenario"] = "pudo_walking_gv"
        summaries.append(s)

    df_summary = pd.DataFrame(summaries)
    df_summary.to_csv(f"{args.output_prefix}_summary.csv", index=False)
    print("\n=== Summary ===")
    print(df_summary.to_string(index=False))


if __name__ == "__main__":
    main()
