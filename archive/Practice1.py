def generate_groups(pending: Sequence[Request], max_group_size: int, vehicle_capacity: int) -> List[Tuple[int, ...]]:
    """Generate candidate request groups tau."""
    requests = list(pending)
    groups: List[Tuple[int, ...]] = []
    by_id = {r.rid: r for r in requests}
    for q in range(1, max_group_size + 1):
        for combo in itertools.combinations(requests, q):
            if sum(r.passengers for r in combo) <= vehicle_capacity:
                groups.append(tuple(sorted(r.rid for r in combo)))
    groups.sort(key=lambda g: (len(g), g))
    _ = by_id
    return groups


def feasible_stop_sequences(group: Tuple[int, ...]) -> Iterable[List[Tuple[str, int]]]:
    """Enumerate pickup/dropoff orders with pickup-before-dropoff precedence."""
    events = []
    for rid in group:
        events.append(("pickup", rid))
        events.append(("dropoff", rid))

    for perm in itertools.permutations(events):
        seen_pickups = set()
        ok = True
        for kind, rid in perm:
            if kind == "pickup":
                seen_pickups.add(rid)
            elif rid not in seen_pickups:
                ok = False
                break
        if ok:
            yield list(perm)


def candidate_nodes(req: Request, tt: TravelTimeCache, params: SimParams, allow_walking: bool) -> Tuple[List[int], List[int]]:
    if not allow_walking:
        return [req.o_node], [req.d_node]
    pickups = tt.walk_candidates(req.o_node, params.omega_walk, params.pudo_candidate_limit)
    dropoffs = tt.walk_candidates(req.d_node, params.omega_walk, params.pudo_candidate_limit)
    if req.o_node not in pickups:
        pickups.insert(0, req.o_node)
    if req.d_node not in dropoffs:
        dropoffs.insert(0, req.d_node)
    return pickups, dropoffs


def evaluate_group_vehicle(
    group: Tuple[int, ...],
    vehicle: Vehicle,
    request_by_id: Dict[int, Request],
    current_time: float,
    tt: TravelTimeCache,
    params: SimParams,
    allow_walking: bool,
) -> Optional[GroupVehicleEdge]:
    """
    Compute cost(tau, v) by enumerating feasible service sequences and PUDO choices.

    This corresponds to a GV-graph edge evaluation. For small groups this exact
    enumeration is easier to understand than the paper's insertion heuristics.
    """
    if vehicle.available_time > current_time:
        return None

    group_requests = [request_by_id[rid] for rid in group]
    if sum(r.passengers for r in group_requests) + len(vehicle.onboard) > vehicle.capacity:
        return None

    # Generate PUDO choices per request.
    pudo_choices: List[List[Tuple[int, int]]] = []
    for req in group_requests:
        pickups, dropoffs = candidate_nodes(req, tt, params, allow_walking)
        choices = []
        for p in pickups:
            walk_o = tt.walk_time(req.o_node, p)
            if walk_o > params.omega_walk:
                continue
            for d in dropoffs:
                walk_d = tt.walk_time(d, req.d_node)
                if walk_d > params.omega_walk:
                    continue
                choices.append((p, d))
        if not choices:
            return None
        pudo_choices.append(choices)

    best: Optional[Tuple[float, float, List[Stop], Dict[int, AssignmentResult]]] = None

    for choice_tuple in itertools.product(*pudo_choices):
        pickup_node = {req.rid: int(choice_tuple[i][0]) for i, req in enumerate(group_requests)}
        dropoff_node = {req.rid: int(choice_tuple[i][1]) for i, req in enumerate(group_requests)}

        for seq in feasible_stop_sequences(group):
            time_now = current_time
            node_now = vehicle.node
            onboard_load = len(vehicle.onboard)
            pickup_time: Dict[int, float] = {}
            dropoff_time: Dict[int, float] = {}
            route: List[Stop] = []
            feasible = True
            added_vehicle_time = 0.0

            for kind, rid in seq:
                req = request_by_id[rid]
                stop_node = pickup_node[rid] if kind == "pickup" else dropoff_node[rid]
                drive = tt.drive_time(node_now, stop_node)
                if not math.isfinite(drive):
                    feasible = False
                    break
                time_now += drive
                added_vehicle_time += drive
                node_now = stop_node

                if kind == "pickup":
                    walk_o = tt.walk_time(req.o_node, pickup_node[rid])
                    passenger_ready = req.t_request + walk_o
                    if time_now < passenger_ready:
                        wait_for_passenger = passenger_ready - time_now
                        time_now = passenger_ready
                        added_vehicle_time += wait_for_passenger
                    wait = time_now - passenger_ready
                    if wait > params.omega_wait:
                        feasible = False
                        break
                    onboard_load += req.passengers
                    if onboard_load > vehicle.capacity:
                        feasible = False
                        break
                    pickup_time[rid] = time_now
                else:
                    if rid not in pickup_time:
                        feasible = False
                        break
                    onboard_load -= req.passengers
                    dropoff_time[rid] = time_now

                route.append(Stop(rid=rid, kind=kind, node=stop_node, scheduled_time=time_now))

            if not feasible:
                continue

            results: Dict[int, AssignmentResult] = {}
            total_cost = 0.0
            for req in group_requests:
                if req.rid not in pickup_time or req.rid not in dropoff_time:
                    feasible = False
                    break
                walk_o = tt.walk_time(req.o_node, pickup_node[req.rid])
                walk_d = tt.walk_time(dropoff_node[req.rid], req.d_node)
                walk_total = walk_o + walk_d
                wait = pickup_time[req.rid] - (req.t_request + walk_o)
                in_vehicle = dropoff_time[req.rid] - pickup_time[req.rid]
                total_arrival = dropoff_time[req.rid] + walk_d
                private_arrival = req.t_request + req.direct_drive
                delay = total_arrival - private_arrival

                if wait > params.omega_wait or delay > params.omega_delay:
                    feasible = False
                    break

                total_cost += req.passengers * (
                    params.p_wait * wait / 60.0
                    + params.p_walk * walk_total / 60.0
                    + params.p_vehicle * max(0.0, in_vehicle - req.direct_drive) / 60.0
                )
                results[req.rid] = AssignmentResult(
                    rid=req.rid,
                    vid=vehicle.vid,
                    accepted=True,
                    wait=wait,
                    walk=walk_total,
                    in_vehicle=in_vehicle,
                    delay=delay,
                    pickup_node=pickup_node[req.rid],
                    dropoff_node=dropoff_node[req.rid],
                )

            if not feasible:
                continue

            total_cost += params.c_operating * added_vehicle_time / 60.0
            if best is None or total_cost < best[0]:
                best = (total_cost, added_vehicle_time, route, results)

    if best is None:
        return None

    cost, added_vehicle_time, route, results = best
    return GroupVehicleEdge(
        edge_id=-1,
        group=group,
        vehicle_id=vehicle.vid,
        cost=cost,
        added_vehicle_time=added_vehicle_time,
        route=route,
        results=results,
    )


def build_gv_graph(
    pending: Sequence[Request],
    vehicles: Sequence[Vehicle],
    current_time: float,
    tt: TravelTimeCache,
    params: SimParams,
    allow_walking: bool,
) -> List[GroupVehicleEdge]:
    request_by_id = {r.rid: r for r in pending}
    max_capacity = max(v.capacity for v in vehicles) if vehicles else 0
    groups = generate_groups(pending, params.max_group_size, max_capacity)

    edges: List[GroupVehicleEdge] = []
    edge_id = 0
    for group in groups:
        for vehicle in vehicles:
            edge = evaluate_group_vehicle(
                group=group,
                vehicle=vehicle,
                request_by_id=request_by_id,
                current_time=current_time,
                tt=tt,
                params=params,
                allow_walking=allow_walking,
            )
            if edge is not None:
                edge.edge_id = edge_id
                edges.append(edge)
                edge_id += 1
    return edges


# -----------------------------
# ILP assignment
# -----------------------------

def solve_assignment_ilp(
    pending: Sequence[Request],
    available_vehicles: Sequence[Vehicle],
    edges: Sequence[GroupVehicleEdge],
    params: SimParams,
) -> Tuple[List[GroupVehicleEdge], List[int]]:
    """Solve the GV-graph assignment problem."""
    problem = pulp.LpProblem("gv_assignment", pulp.LpMinimize)

    x = {
        e.edge_id: pulp.LpVariable(f"x_{e.edge_id}", lowBound=0, upBound=1, cat="Binary")
        for e in edges
    }
    z = {
        r.rid: pulp.LpVariable(f"z_{r.rid}", lowBound=0, upBound=1, cat="Binary")
        for r in pending
    }

    problem += (
        pulp.lpSum(x[e.edge_id] * e.cost for e in edges)
        + pulp.lpSum(z[r.rid] * params.rejection_penalty for r in pending)
    )

    for r in pending:
        incident = [x[e.edge_id] for e in edges if r.rid in e.group]
        problem += pulp.lpSum(incident) + z[r.rid] >= 1, f"cover_request_{r.rid}"

    for v in available_vehicles:
        incident = [x[e.edge_id] for e in edges if e.vehicle_id == v.vid]
        problem += pulp.lpSum(incident) <= 1, f"vehicle_once_{v.vid}"

    solver = pulp.PULP_CBC_CMD(msg=False)
    status = problem.solve(solver)
    if pulp.LpStatus[status] not in {"Optimal", "Feasible"}:
        return [], [r.rid for r in pending]

    selected = [e for e in edges if pulp.value(x[e.edge_id]) is not None and pulp.value(x[e.edge_id]) > 0.5]
    rejected = [r.rid for r in pending if pulp.value(z[r.rid]) is not None and pulp.value(z[r.rid]) > 0.5]
    return selected, rejected


# -----------------------------
# Dynamic simulation
# -----------------------------

def run_simulation(
    requests: List[Request],
    vehicles: List[Vehicle],
    tt: TravelTimeCache,
    params: SimParams,
    allow_walking: bool,
) -> pd.DataFrame:
    results: Dict[int, AssignmentResult] = {}
    req_by_time = sorted(requests, key=lambda r: r.t_request)
    pending: List[Request] = []
    cursor = 0

    if not req_by_time:
        return pd.DataFrame()

    t0 = 0
    t1 = int(math.ceil(max(r.t_request for r in req_by_time) / params.batch_seconds) * params.batch_seconds)
    vehicle_by_id = {v.vid: v for v in vehicles}

    desc = f"Sim GV-DARP allow_walking={allow_walking}"
    for current_time in tqdm(range(t0, t1 + params.batch_seconds, params.batch_seconds), desc=desc):
        while cursor < len(req_by_time) and req_by_time[cursor].t_request <= current_time:
            pending.append(req_by_time[cursor])
            cursor += 1

        if not pending:
            continue

        # Remove requests whose maximum waiting time expired.
        still_pending: List[Request] = []
        for req in pending:
            if current_time - req.t_request > params.omega_wait:
                results[req.rid] = AssignmentResult(rid=req.rid, vid=None, accepted=False)
            else:
                still_pending.append(req)
        pending = still_pending
        if not pending:
            continue

        available_vehicles = [v for v in vehicles if v.available_time <= current_time]
        if not available_vehicles:
            continue

        edges = build_gv_graph(
            pending=pending,
            vehicles=available_vehicles,
            current_time=current_time,
            tt=tt,
            params=params,
            allow_walking=allow_walking,
        )
        if not edges:
            continue

        selected_edges, rejected_ids = solve_assignment_ilp(
            pending=pending,
            available_vehicles=available_vehicles,
            edges=edges,
            params=params,
        )

        assigned_ids = set()
        for edge in selected_edges:
            veh = vehicle_by_id[edge.vehicle_id]
            veh.route = edge.route
            veh.available_time = current_time + edge.added_vehicle_time
            veh.vht += edge.added_vehicle_time
            if edge.route:
                veh.node = edge.route[-1].node
            for rid, res in edge.results.items():
                results[rid] = res
                assigned_ids.add(rid)

        for rid in rejected_ids:
            if rid not in assigned_ids:
                results[rid] = AssignmentResult(rid=rid, vid=None, accepted=False)

        pending = [r for r in pending if r.rid not in assigned_ids and r.rid not in rejected_ids]

    for req in pending:
        if req.rid not in results:
            results[req.rid] = AssignmentResult(rid=req.rid, vid=None, accepted=False)

    rows = []
    for r in requests:
        res = results.get(r.rid, AssignmentResult(rid=r.rid, vid=None, accepted=False))
        rows.append(res.__dict__)
    return pd.DataFrame(rows)


def summarize(df: pd.DataFrame, vehicles: List[Vehicle]) -> Dict[str, float]:
    accepted = df[df["accepted"]] if not df.empty else pd.DataFrame()
    total = len(df)
    return {
        "requests": total,
        "accepted": int(len(accepted)),
        "rejected": int(total - len(accepted)),
        "rejection_rate": float(1 - len(accepted) / total) if total else math.nan,
        "avg_wait_min": float(accepted["wait"].mean() / 60.0) if len(accepted) else math.nan,
        "avg_walk_min": float(accepted["walk"].mean() / 60.0) if len(accepted) else math.nan,
        "avg_delay_min": float(accepted["delay"].mean() / 60.0) if len(accepted) else math.nan,
        "vht_hours": float(sum(v.vht for v in vehicles) / 3600.0),
        "walk_share": float((accepted["walk"] > 1e-6).mean()) if len(accepted) else math.nan,
    }


