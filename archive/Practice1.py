

"""
NYC Taxi PUDO DARP Prototype
============================

This script is structured to follow the assignment framework of:
Fielbaum, Bai, Alonso-Mora (2021),
"On-demand ridesharing with optimized pick-up and drop-off walking locations".

Core structure implemented here
-------------------------------
1. Load NYC TLC taxi requests.
2. Build a Manhattan road network.
3. Convert taxi trips to DARP requests r = (origin, destination, request time, passengers).
4. Run a dynamic batched assignment every delta seconds.
5. Build feasible request groups tau.
6. Build the GV-graph: feasible group-vehicle edges (tau, v) with cost(tau, v).
7. Solve the assignment problem as an ILP.
8. Compare door-to-door and PUDO walking scenarios.

Important simplifications
-------------------------
This is not yet a perfect reproduction of the paper. It is a clean research prototype
that matches the paper's algorithmic structure.

Simplifications compared with the full paper:
- group size is limited by --max-group-size, default 2;
- existing onboard passengers are represented by vehicle stop sequences, but no advanced
  reassignment policy is implemented yet;
- route sequence enumeration is exact for small groups instead of using all paper heuristics;
- PUDO candidates are generated by walking-radius search with a candidate limit.

Install
-------
pip install pandas numpy geopandas osmnx networkx scipy pyarrow tqdm pulp scikit-learn

Example
-------
python Practice1.py \
  --taxi-file yellow_tripdata_2026-03.parquet \
  --zone-lookup taxi_zone_lookup.csv \
  --zone-shp taxi_zones_2/taxi_zones.shp \
  --n-vehicles 300 \
  --max-requests 1500 \
  --max-group-size 2 \
  --mode compare
"""

