def build_graph(place: str) -> nx.MultiDiGraph:
    print(f"Building road network from OSM: {place}")
    G = ox.graph_from_place(place, network_type="drive", simplify=True)
    G = ox.add_edge_speeds(G, fallback=30)
    G = ox.add_edge_travel_times(G)
    return G


def nearest_nodes(G: nx.MultiDiGraph, lon: Iterable[float], lat: Iterable[float]) -> np.ndarray:
    lon_list = list(lon)
    lat_list = list(lat)
    if len(lon_list) == 0:
        return np.array([], dtype=int)
    try:
        return np.array(ox.distance.nearest_nodes(G, X=lon_list, Y=lat_list), dtype=int)
    except ImportError as exc:
        raise ImportError(
            "OSMnx needs scikit-learn to run nearest_nodes on an unprojected graph. Install it with:\n"
            "pip install scikit-learn"
        ) from exc


class TravelTimeCache:
    """Shortest-path travel-time cache for vehicle and walking times."""

    def __init__(self, G_drive: nx.MultiDiGraph, walking_speed_mps: float):
        self.G_drive = G_drive
        self.G_walk = self._make_walk_graph(G_drive, walking_speed_mps)

    @staticmethod
    def _make_walk_graph(G_drive: nx.MultiDiGraph, walking_speed_mps: float) -> nx.Graph:
        G_walk = nx.Graph()
        for u, v, data in G_drive.edges(data=True):
            length = float(data.get("length", 1.0))
            t = length / walking_speed_mps
            if G_walk.has_edge(u, v):
                if t < G_walk[u][v]["walk_time"]:
                    G_walk[u][v]["walk_time"] = t
            else:
                G_walk.add_edge(u, v, walk_time=t)
        return G_walk

    @lru_cache(maxsize=1_000_000)
    def drive_time(self, u: int, v: int) -> float:
        if u == v:
            return 0.0
        try:
            return float(nx.shortest_path_length(self.G_drive, u, v, weight="travel_time"))
        except (nx.NetworkXNoPath, nx.NodeNotFound):
            return math.inf

    @lru_cache(maxsize=1_000_000)
    def walk_time(self, u: int, v: int) -> float:
        if u == v:
            return 0.0
        try:
            return float(nx.shortest_path_length(self.G_walk, u, v, weight="walk_time"))
        except (nx.NetworkXNoPath, nx.NodeNotFound):
            return math.inf

    @lru_cache(maxsize=200_000)
    def walk_candidates_cached(self, node: int, omega_walk: float, limit: int) -> Tuple[int, ...]:
        lengths = nx.single_source_dijkstra_path_length(
            self.G_walk,
            node,
            cutoff=omega_walk,
            weight="walk_time",
        )
        ordered = sorted(lengths.items(), key=lambda kv: kv[1])
        return tuple(int(n) for n, _ in ordered[:limit])

    def walk_candidates(self, node: int, omega_walk: float, limit: int) -> List[int]:
        return list(self.walk_candidates_cached(int(node), float(omega_walk), int(limit)))


