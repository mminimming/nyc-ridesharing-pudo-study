@dataclass(frozen=True)
class Request:
    """DARP request r = (origin, destination, request time, passenger count)."""

    rid: int
    t_request: float
    o_node: int
    d_node: int
    passengers: int
    direct_drive: float


@dataclass
class Stop:
    """A planned vehicle stop."""

    rid: int
    kind: str  # "pickup" or "dropoff"
    node: int
    scheduled_time: float = math.nan


@dataclass
class Vehicle:
    """Vehicle state used in the GV-graph assignment."""

    vid: int
    node: int
    capacity: int = 4
    available_time: float = 0.0
    onboard: Tuple[int, ...] = field(default_factory=tuple)
    route: List[Stop] = field(default_factory=list)
    vht: float = 0.0


@dataclass
class AssignmentResult:
    rid: int
    vid: Optional[int]
    accepted: bool
    wait: float = math.nan
    walk: float = math.nan
    in_vehicle: float = math.nan
    delay: float = math.nan
    pickup_node: Optional[int] = None
    dropoff_node: Optional[int] = None


@dataclass
class GroupVehicleEdge:
    """One GV-graph edge: assigning request group tau to vehicle v."""

    edge_id: int
    group: Tuple[int, ...]
    vehicle_id: int
    cost: float
    added_vehicle_time: float
    route: List[Stop]
    results: Dict[int, AssignmentResult]


@dataclass
class SimParams:
    batch_seconds: int = 60
    omega_wait: float = 5 * 60
    omega_delay: float = 10 * 60
    omega_walk: float = 2 * 60
    walking_speed_mps: float = 1.35
    p_wait: float = 2.0
    p_walk: float = 2.0
    p_vehicle: float = 1.0
    c_operating: float = 1.5
    rejection_penalty: float = 80.0
    pudo_candidate_limit: int = 8
    max_group_size: int = 2


